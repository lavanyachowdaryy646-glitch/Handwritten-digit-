# PROJECT 4: HANDWRITTEN DIGIT IMAGE CLASSIFIER
# Using Python, TensorFlow and Keras

import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
import os

from tensorflow.keras import layers, models
from sklearn.metrics import confusion_matrix, classification_report, ConfusionMatrixDisplay

print("TensorFlow Version:", tf.__version__)

# 1. LOAD MNIST DATASET
(x_train, y_train), (x_test, y_test) = tf.keras.datasets.mnist.load_data()

print("Training images:", x_train.shape)
print("Testing images:", x_test.shape)

# 2. NORMALIZE IMAGES
x_train = x_train.astype("float32") / 255.0
x_test = x_test.astype("float32") / 255.0

# 3. BUILD CNN MODEL
model = models.Sequential([
    layers.Input(shape=(28, 28, 1)),
    layers.Conv2D(32, (3, 3), activation="relu"),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation="relu"),
    layers.MaxPooling2D((2, 2)),
    layers.Flatten(),
    layers.Dense(128, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(10, activation="softmax")
])

# 4. COMPILE MODEL
model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

# 5. TRAIN MODEL
history = model.fit(
    x_train[..., np.newaxis],
    y_train,
    epochs=5,
    batch_size=64,
    validation_split=0.1
)

# 6. TEST MODEL
test_loss, test_accuracy = model.evaluate(
    x_test[..., np.newaxis], y_test, verbose=0
)

print("\nTest Loss:", test_loss)
print("Test Accuracy:", round(test_accuracy * 100, 2), "%")

# 7. TRAINING AND VALIDATION ACCURACY GRAPH
plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")
plt.title("Training and Validation Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()

# 8. TRAINING AND VALIDATION LOSS GRAPH
plt.subplot(1, 2, 2)
plt.plot(history.history["loss"], label="Training Loss")
plt.plot(history.history["val_loss"], label="Validation Loss")
plt.title("Training and Validation Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()

plt.tight_layout()
plt.savefig("training_graphs.png")
plt.show()

# 9. PREDICT TEST IMAGES
predictions = model.predict(x_test[:10, ..., np.newaxis], verbose=0)
predicted_digits = np.argmax(predictions, axis=1)

plt.figure(figsize=(12, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(x_test[i], cmap="gray")
    plt.title(f"Predicted: {predicted_digits[i]}\nActual: {y_test[i]}")
    plt.axis("off")

plt.tight_layout()
plt.savefig("digit_predictions.png")
plt.show()

# 10. CONFUSION MATRIX
all_predictions = model.predict(x_test[..., np.newaxis], verbose=0)
predicted_labels = np.argmax(all_predictions, axis=1)

cm = confusion_matrix(y_test, predicted_labels)

display = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=range(10)
)
display.plot(cmap="Blues", values_format="d")
plt.title("MNIST Confusion Matrix")
plt.savefig("confusion_matrix.png")
plt.show()

# 11. SAVE TRAINED MODEL
model.save("mnist_image_classifier.keras")

print("\nPROJECT COMPLETED SUCCESSFULLY!")
print("Model and graphs saved.")

